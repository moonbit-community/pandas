"""Generates the Unicode case-mapping tables of `str_to_lowercase` /
`str_to_uppercase` (src/pl/case_data.mbt) by asking polars itself, the same
way `char_width.py` measures widths: no Python Unicode database is involved,
so the tables carry exactly the Unicode version polars 2.1.0 was built with.

Run from the repository root, on a machine that has polars 2.1.0:

    /data/lly-moonbit/polars-venv/bin/python docs/golden/scripts/case_tables.py && moon fmt

What is measured, for every code point `c` that is not a surrogate:

* `lower(c)`, `upper(c)`: `pl.Series([chr(c)]).str.to_lowercase()` /
  `to_uppercase()`. The result has 1 to 3 characters (`ß` -> `SS`,
  `İ` -> `i` + U+0307, `ΐ` -> 3 characters). Only code points that map to
  something else are stored. These are the context-free mappings of Rust's
  `str::to_lowercase`/`to_uppercase`.
* The one context-dependent rule of Rust's `to_lowercase`: `Σ` becomes `ς`
  (final sigma) instead of `σ` when a cased letter comes before it and no cased
  letter after it, skipping case-ignorable characters on both sides. The two
  sets that rule needs are derived by probing:

      final("A" + c + "Σ")  = ignorable(c) or cased(c)
      final("1" + c + "Σ")  = cased(c) and not ignorable(c)

  so `ignorable(c) = final("AcΣ") and not final("1cΣ")` and, for a character
  that is not ignorable, `cased(c) = final("1cΣ")`. Both are stored as
  inclusive ranges (`cased` excludes the ignorable characters, which the rule
  skips before it looks at `cased`).

Layout of the generated file (all `FixedArray[Int32]`):

* `case_lower_map`, `case_upper_map`: stride 5, `cp, n, c1, c2, c3` (`n` is the
  number of result characters, unused slots are 0), ascending by `cp`.
* `case_ignorable_ranges`, `case_cased_ranges`: stride 2, `first, last`.
"""
import os
import sys

import polars as pl

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

SIGMA = "Σ"
CHUNK = 65536


def codepoints():
    return [c for c in range(0x110000) if not (0xD800 <= c <= 0xDFFF)]


def map_table(cps, fn):
    """`[(cp, [targets])]` for every code point whose mapping is not itself."""
    out = []
    for i in range(0, len(cps), CHUNK):
        part = cps[i:i + CHUNK]
        res = fn(pl.Series([chr(c) for c in part])).to_list()
        for c, r in zip(part, res):
            if r != chr(c):
                targets = [ord(x) for x in r]
                assert 1 <= len(targets) <= 3, (hex(c), r)
                out.append((c, targets))
    return out


def sigma_probe(cps, build, pick):
    """Boolean per code point: `pick(lowercased string)` for `build(c)`."""
    flags = []
    for i in range(0, len(cps), CHUNK):
        part = cps[i:i + CHUNK]
        res = pl.Series([build(chr(c)) for c in part]).str.to_lowercase().to_list()
        flags.extend(pick(r) for r in res)
    return flags


def ranges(cps, flags):
    out = []
    for c, f in zip(cps, flags):
        if not f:
            continue
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def main():
    cps = codepoints()
    lower = map_table(cps, lambda s: s.str.to_lowercase())
    upper = map_table(cps, lambda s: s.str.to_uppercase())

    final_a = sigma_probe(cps, lambda c: "A" + c + SIGMA, lambda r: r[-1] == "ς")
    final_1 = sigma_probe(cps, lambda c: "1" + c + SIGMA, lambda r: r[-1] == "ς")
    ignorable = [a and not b for a, b in zip(final_a, final_1)]
    cased = [b for b in final_1]
    # sanity: the probes agree with the rule on a few known characters
    idx = {c: i for i, c in enumerate(cps)}
    assert not ignorable[idx[ord("a")]] and cased[idx[ord("a")]]
    assert ignorable[idx[ord(".")]] and not cased[idx[ord(".")]]
    assert ignorable[idx[0x0301]] and not cased[idx[0x0301]]
    assert not ignorable[idx[ord(" ")]] and not cased[idx[ord(" ")]]

    ign_r = ranges(cps, ignorable)
    cased_r = ranges(cps, cased)

    def flat_map(tab):
        nums = []
        for c, t in tab:
            nums += [c, len(t)] + t + [0] * (3 - len(t))
        return nums

    def flat_ranges(rs):
        return [x for r in rs for x in r]

    def fmt(name, doc, nums):
        body = ", ".join(hex(n) for n in nums)
        return f"///|\n/// {doc}\nlet {name} : FixedArray[Int32] = [{body}]\n"

    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    path = os.path.join(root, "src", "pl", "case_data.mbt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by docs/golden/scripts/case_tables.py from polars "
            f"{pl.__version__}'s own\n// output. Do not edit by hand; run the "
            "script again instead (see its docstring).\n\n"
        )
        f.write(fmt("case_lower_map", "`cp, n, c1, c2, c3` per code point whose lower case is not itself.", flat_map(lower)))
        f.write("\n")
        f.write(fmt("case_upper_map", "`cp, n, c1, c2, c3` per code point whose upper case is not itself.", flat_map(upper)))
        f.write("\n")
        f.write(fmt("case_ignorable_ranges", "`first, last` of the case-ignorable code points (skipped by the final-sigma rule).", flat_ranges(ign_r)))
        f.write("\n")
        f.write(fmt("case_cased_ranges", "`first, last` of the cased code points that are not case-ignorable.", flat_ranges(cased_r)))
    print(f"polars {pl.__version__}: lower {len(lower)}, upper {len(upper)}, "
          f"ignorable ranges {len(ign_r)}, cased ranges {len(cased_r)}")


main()
