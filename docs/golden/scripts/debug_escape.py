"""Generates the table of characters that Rust's `Debug` for `str` writes as
`\\u{..}` (src/pl/debug_escape_data.mbt), by reading polars' own error text.

Run from the repository root, on a machine that has polars 2.1.0:

    /data/lly-moonbit/polars-venv/bin/python docs/golden/scripts/debug_escape.py && moon fmt

polars quotes a missing column name with Rust's `Debug`:

    pl.DataFrame({"column": [1]}).get_column(name)  ->  ColumnNotFoundError: "<name>" not found

so the table is read off that text for every code point (U+D800-U+DFFF are not
characters and are left out). A character is "escaped" when the text is
`\\u{<lowercase hex>}`; the other special cases (`\\0`, `\\t`, `\\r`, `\\n`, `\\"`,
`\\\\`) are fixed in `debug_quote` and checked here. The ranges are stored flat as
`first, last` (inclusive), in ascending order. The script stops with an error when
a character is neither written as itself nor in one of the forms above.
"""
import os

import polars as pl

df = pl.DataFrame({"column": [1]})
SPECIAL = {"\0": "\\0", "\t": "\\t", "\r": "\\r", "\n": "\\n", '"': '\\"', "\\": "\\\\"}


def debug_text(ch):
    try:
        df.get_column(ch)
        raise AssertionError(hex(ord(ch)))
    except pl.exceptions.ColumnNotFoundError as e:
        text = str(e).split("\n")[0]
    assert text.startswith('"') and text.endswith('" not found'), (hex(ord(ch)), text)
    return text[1 : -len('" not found')]


def main():
    ranges = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        text = debug_text(ch)
        if ch in SPECIAL:
            assert text == SPECIAL[ch], (hex(cp), text)
            continue
        if text == ch:
            continue
        assert text == "\\u{%x}" % cp, (hex(cp), text)
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    flat = [v for r in ranges for v in r]
    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    lines = [
        "// Generated by docs/golden/scripts/debug_escape.py from polars 2.1.0's own",
        "// error text. Do not edit by hand; run the script again instead.",
        "//",
        "// The code points that Rust's `Debug` for `str` writes as `\\u{..}`, as",
        "// inclusive ranges stored flat as `first, last`, in ascending order",
        "// (`\\0`, `\\t`, `\\r`, `\\n`, `\"` and `\\` are not in the table).",
        "",
        "///|",
        "let debug_escape_ranges : FixedArray[Int32] = [",
    ]
    for i in range(0, len(flat), 12):
        lines.append("  " + ", ".join(hex(v) for v in flat[i : i + 12]) + ",")
    lines.append("]")
    with open(os.path.join(root, "src", "pl", "debug_escape_data.mbt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"polars {pl.__version__}: {len(ranges)} ranges")


main()
